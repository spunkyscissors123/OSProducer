// Generates thin page files for both the live app (/(app)/...) and demo (/demo/...) from one route table.
// Each page just picks a data repo and renders the shared view. Run: node scripts/gen-routes.mjs
import { mkdirSync, writeFileSync } from "node:fs";

const ROUTES = [
  ["dashboard", "DashboardView", "dashboard", "Dashboard"],
  ["prospects", "ProspectsView", "prospects", "Prospects"],
  ["prospects/new", "NewProspectView", "prospect-form-page", "Add prospect"],
  ["prospects/import", "ImportView", "import", "Import prospects"],
  ["prospects/[id]", "ProspectDetailView", "prospect-detail", "Prospect"],
  ["prospects/[id]/edit", "EditProspectView", "prospect-form-page", "Edit prospect"],
  ["finder", "FinderView", "finder", "Prospect Finder"],
  ["pipeline", "PipelineView", "pipeline", "Sales Pipeline"],
  ["renewals", "RenewalsView", "renewals", "Renewal Calendar"],
  ["tasks", "TasksView", "tasks", "Tasks"],
  ["assistant", "AssistantView", "assistant", "AI Assistant"],
  ["analytics", "AnalyticsView", "analytics", "Production Analytics"],
  ["settings", "SettingsView", "settings", "Settings"],
  ["billing", "BillingView", "billing", "Billing"],
];

for (const [route, view, file, title] of ROUTES) {
  for (const mode of ["live", "demo"]) {
    const dir = mode === "live" ? `src/app/(app)/${route}` : `src/app/demo/${route}`;
    const getter = mode === "live" ? "getLiveRepo" : "getDemoRepo";
    const mod = mode === "live" ? "live-repo" : "demo-repo";
    mkdirSync(dir, { recursive: true });
    writeFileSync(
      `${dir}/page.tsx`,
      `// Generated by scripts/gen-routes.mjs — edit the view in src/views/${file}.tsx instead.
import type { Metadata } from "next";
import { ${view} } from "@/views/${file}";
import { ${getter} } from "@/lib/data/${mod}";

export const metadata: Metadata = { title: "${title}" };

type Props = { params: Promise<Record<string, string>>; searchParams: Promise<Record<string, string | string[] | undefined>> };

export default async function Page({ params, searchParams }: Props) {
  return <${view} repo={await ${getter}()} params={await params} searchParams={await searchParams} />;
}
`,
    );
  }
}
console.log(`Generated ${ROUTES.length * 2} pages`);
